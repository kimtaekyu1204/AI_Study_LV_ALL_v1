# 2. 컴파일러와 인터프리터의 개념
# ============================================================================

"""
프로그래밍 언어의 실행 방식:

(1) 컴파일러 (Compiler)
    - 정의: 프로그램 코드 전체를 기계어로 미리 번역하는 도구
    - 특징:
      * 실행 전에 전체 코드를 한 번에 번역한다.
      * 번역 후 실행 속도가 빠르다.
      * 오류를 전체 코드 스캔 후 일괄 보고한다.
    - 예시: Java, C, C++
    - 실행 프로세스:
      * 소스 코드 작성 → 컴파일 → 기계어 파일(실행파일) 생성 → 실행

(2) 인터프리터 (Interpreter)
    - 정의: 프로그램 코드를 한 줄씩 읽어서 실시간으로 해석 및 실행하는 도구
    - 특징:
      * 코드를 한 줄씩 읽으면서 바로 실행한다.
      * 오류가 발생한 줄에서 즉시 중단된다.
      * 개발과 테스트가 빠르다.
      * 실행 속도는 컴파일러보다 느리다.
    - 예시: Python, JavaScript
    - 실행 프로세스:
      * 소스 코드 작성 → 인터프리터 실행 → 한 줄씩 해석 및 실행
"""

