"""
(1) 컴파일 언어 사례

    Java:
    - 특징: "Write Once, Run Anywhere" (WORA)
    - 사용 분야: 엔터프라이즈 소프트웨어, 안드로이드 앱
    - 실행 과정: Java 소스코드 → 자바 컴파일러 → 바이트코드 → JVM 해석 실행

    C:
    - 특징: 저수준 메모리 접근, 높은 성능
    - 사용 분야: 운영체제, 임베디드 시스템
    - 매우 빠른 실행 속도

    C++:
    - 특징: C의 기능 + 객체지향 프로그래밍
    - 사용 분야: 게임, 고성능 어플리케이션
    - 복잡하지만 강력한 성능

(2) 인터프리터 언어 사례

    Python:
    - 특징: 간단한 문법, 높은 가독성
    - 사용 분야: 데이터 분석, AI/머신러닝, 웹 개발
    - 개발 속도가 빠르다.
    - 프로세스:
      * 프로그램 코드를 하나하나 읽어 들인다.
      * 곧바로 해석해서 컴퓨터에게 실행시킨다.
      * 한 줄씩 실시간으로 해석되므로 오류가 나면 그 지점에서 중단된다.

    JavaScript:
    - 특징: 웹 브라우저에서 실행 가능
    - 사용 분야: 웹 프론트엔드, Node.js 백엔드
    - 동적 타입 언어
"""

