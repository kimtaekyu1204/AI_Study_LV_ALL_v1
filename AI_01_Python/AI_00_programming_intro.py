# 간단한 예시: 두 수의 합 계산
def add_two_numbers(a, b):
    """
    두 수를 더하는 함수

    Args:
        a: 첫 번째 숫자
        b: 두 번째 숫자

    Returns:
        두 수의 합

    프로세스:
    1. 함수 정의 (인터프리터가 읽음)
    2. 함수 호출 (실행)
    3. 연산 수행 (한 줄씩 실행)
    4. 결과 반환
    """
    return a + b

# 인터프리터 실행 예시
result = add_two_numbers(5, 3)  # 한 줄씩 실행되며 result에 8이 저장됨
print(f"계산 결과: {result}")  # 다음 줄 실행

# 더 복잡한 예시: 조건문 활용
def classify_number(num):
    """
    숫자를 분류하는 함수

    인터프리터 실행 과정:
    1. if 문 검사 (라인 1)
    2. 조건 만족 시 해당 블록 실행 (라인 2)
    3. 다음 라인으로 진행
    """
    if num > 0:
        return "양수"
    elif num < 0:
        return "음수"
    else:
        return "0"

# 테스트
print(classify_number(10))   # 양수 (한 줄씩 실행되면서 즉시 결과 출력)
print(classify_number(-5))   # 음수
print(classify_number(0))    # 0

