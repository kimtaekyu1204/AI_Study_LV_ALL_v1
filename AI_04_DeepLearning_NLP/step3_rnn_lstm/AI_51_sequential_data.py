# 2. 피드포워드 신경망의 한계
# ============================================================================

# 피드포워드 신경망(FNN: Feedforward Neural Network)의 정의:
# 
# 정의: 데이터의 흐름이 앞으로만 진행되는 신경망
# 특징: 이전 데이터를 기억하지 않는다
# 
# 작동 원리:
# 1. 입력층 → 은닉층 → 출력층
# 2. 각 샘플(배치)에 대해 정방향 계산 수행
# 3. 샘플 처리 후 버려짐 (재사용 안 함)
# 4. 다음 샘플 입력
# 5. 반복
# 
# 핵심 특징: 메모리 없음
# - 이전에 처리한 데이터를 다음 샘플에 사용하지 않음
# - 각 샘플은 독립적으로 처리됨
# 
# FNN의 계층 구조:
# 입력 → Dense층 → ReLU → Dense층 → ReLU → 출력
#         (완전연결)     (활성화)  (완전연결)
# 
# 이미지 분류에서는 작동 잘함:
# - MNIST: 이미지들이 독립적
# - 각 이미지를 어떤 순서로 처리해도 결과 같음
# 
# 하지만 순차 데이터에서는 문제:
# - 텍스트: 단어의 맥락이 중요
# - 예: "I like you" vs "You like I"
# - 문장에서 단어의 순서는 의미를 결정짓는 핵심 요소
# 
# FNN의 한계:
# - 이전 정보를 활용하지 못함
# - 특히 긴 시퀀스에서 정보 손실
# - 동적 길이의 시퀀스 처리 어려움

# ============================================================================
# 3. 순환 신경망 (RNN)의 개념
# ============================================================================

# 순환 신경망(RNN: Recurrent Neural Network)의 정의:
# 
# 정의: 이전 데이터가 다음 데이터 처리에 재사용되는 신경망
# 특징: 메모리를 가지고 있다 (은닉상태)
# 
# 핵심 차이:
# FNN: 데이터 흐름이 앞으로만 진행 (일방통행)
# RNN: 데이터가 순환하면서 이전 정보 활용 (순환 구조)
# 
# RNN의 구조:
# 
# 기본 RNN 셀:
# ┌─────────────────────┐
# │                     │
# h(t-1) ──Wh──┐       │
#              ├──┐    │
# x(t) ──Wx───┘  ├─ activation ──h(t)
#              ├──┘    │
#              └────────│
#              (기본 연산)
# 
# RNN의 특징:
# 1. 입력 가중치 (Wx): 현재 입력에 곱해짐
# 2. 순환 가중치 (Wh): 이전 은닉상태에 곱해짐
# 3. 이 둘을 더해서 활성화 함수 통과
# 4. 결과가 다음 타임스텝의 입력이 됨 (기억)
# 
# 예시: 영화 댓글 감정 분석
# 
# "이 영화는 최고입니다"
# - 단어 1: "이" → 정중한 시작
# - 단어 2: "영화는" → 영화를 이야기하는 중
# - 단어 3: "최고입니다" → 긍정적 표현
# 
# RNN 없이 (FNN):
# - "최고입니다"라는 단어만 봐서는 긍정 판단 가능
# - 하지만 문맥 이해 부족
# 
# RNN으로 (순환):
# - "이" 처리 후 상태 1 저장
# - "영화는" + 상태 1 → 상태 2 저장
# - "최고입니다" + 상태 2 → 최종 상태
# - 전체 문맥을 고려한 판단
# 
# 또 다른 예시: "나만 당할수 없다" + "꼭 보세요"
# - 앞 댓글만으로는 부정적으로 보임
# - 하지만 다음 댓글의 "꼭 보세요"까지 봐야 전체 의미 이해
# - RNN: 각 단어를 순서대로 처리하면서 문맥 축적
# 
# RNN의 역할:
# 1. 이전에 입력된 데이터를 기억한다
# 2. 현재 입력과 기억된 정보를 결합한다
# 3. 더 나은 판단을 할 수 있다
# 4. 특히 긴 시퀀스에서 효과적이다

# ============================================================================
# 4. 타임스텝과 은닉상태
# ============================================================================

# 타임스텝(Timestep)의 개념:
# 
# 정의: 순환 신경망이 시퀀스를 처리하는 한 단계
# 특징: 한 번에 한 아이템(단어, 픽셀, 값)을 처리
# 용어: 시간 단계, 시간 인덱스
# 
# 예시: 문장 "I am a boy" (4개 단어)
# - 타임스텝 1: "I" 처리
# - 타임스텝 2: "am" 처리
# - 타임스텝 3: "a" 처리
# - 타임스텝 4: "boy" 처리
# 
# RNN 셀 상태 전이:
# 
# 초기 상태 h(0): 모두 0으로 초기화 (기억이 없는 상태)
# 
# 타임스텝 1:
# 입력: "I" (벡터로 표현, 예: [0.5, 0.3, 0.8])
# 은닉상태: h(0) = [0, 0, 0]
# 연산: h(1) = activation(Wx * input + Wh * h(0))
# 결과: h(1) = [0.3, 0.2, 0.6] (첫 번째 단어 정보 저장)
# 
# 타임스텝 2:
# 입력: "am" (벡터로 표현)
# 은닉상태: h(1) = [0.3, 0.2, 0.6] (이전 단어 정보)
# 연산: h(2) = activation(Wx * input + Wh * h(1))
# 결과: h(2) = [0.5, 0.4, 0.7] (첫 + 두 번째 단어 정보)
# 
# 타임스텝 3:
# 입력: "a"
# 은닉상태: h(2) = [0.5, 0.4, 0.7] (누적된 정보)
# 연산: h(3) = activation(Wx * input + Wh * h(2))
# 결과: h(3) = [0.6, 0.5, 0.8] (첫 + 두 + 세 번째 단어 정보)
# 
# 타임스텝 4:
# 입력: "boy"
# 은닉상태: h(3) = [0.6, 0.5, 0.8] (누적된 정보)
# 연산: h(4) = activation(Wx * input + Wh * h(3))
# 결과: h(4) = [0.7, 0.6, 0.9] (전체 문장 정보)
# 
# 정보의 누적:
# - 타임스텝이 오래될수록 순환되는 정보는 희미해진다
# - 이전 단계의 정보가 계속 축적되지만, 거리가 멀수록 영향 감소
# - 이것이 LSTM/GRU가 필요한 이유 (장기 의존성 문제)
# 
# 은닉상태(Hidden State)의 정의:
# 
# 정의: 순환 신경망이 가지고 있는 기억 또는 상태
# 용어: 은닉 상태, 숨겨진 상태, 컨텍스트 벡터
# 
# 역할:
# 1. 이전 정보를 저장한다
# 2. 현재와 미래의 처리에 사용된다
# 3. 모델의 메모리 역할
# 
# 특징:
# - 고정된 크기의 벡터
# - 각 타임스텝마다 업데이트됨
# - RNN 셀의 출력이자 다음 입력
# 
# 셀(Cell)의 개념:
# 
# 정의: RNN에서 한 층(layer)을 나타내는 단위
# 특징:
# 1. 여러 뉴런을 포함하지만, 하나의 셀로 표현
# 2. 모든 뉴런이 동일한 가중치를 공유 (가중치 공유)
# 3. 각 타임스텝에서 동일한 셀이 반복 사용
# 
# 시각화:
# RNN 셀 (펼치지 않음):
# ┌──────┐
# │ RNN  │ ──h──
# ├──────┤ (은닉상태)
# │Cell  │
# └──────┘
# 
# RNN 셀을 타임스텝으로 펼친 것:
# ┌──────┐   ┌──────┐   ┌──────┐   ┌──────┐
# │ Cell │──→│ Cell │──→│ Cell │──→│ Cell │
# ├──────┤   ├──────┤   ├──────┤   ├──────┤
# │  t=1 │   │  t=2 │   │  t=3 │   │  t=4 │
# └──────┘   └──────┘   └──────┘   └──────┘
#   I         am         a         boy
# 
# "셀을 타임스텝으로 펼쳤다" = 같은 셀이 시간을 따라 반복된다

# ============================================================================
# 5. 활성화 함수와 가중치
# ============================================================================

# 활성화 함수 (Activation Function)
# 
# 일반적으로 사용되는 활성화 함수: tanh (하이퍼볼릭 탄젠트)
# 
# 정의: tanh는 쌍곡탄젠트 함수
# 범위: -1 ~ +1 사이의 값 출력
# 
# 비교:
# - Sigmoid: 0 ~ 1 범위 (이진 분류에 주로 사용)
# - tanh: -1 ~ +1 범위 (RNN에 주로 사용)
# 
# 왜 RNN에서 tanh를 사용하는가?
# - 대칭성: -1과 +1 사이의 대칭적 범위
# - 기울기: sigmoid보다 더 가파른 기울기 (역전파가 더 효율적)
# - 실제로는 활성화 함수를 생략하고 표현하는 경우도 많음
# 
# 주의:
# - RNN 그림을 그릴 때 활성화 함수를 표시하지 않는 경우가 있다
# - 이는 그림의 복잡함을 피하기 위함
# - 하지만 실제로는 활성화 함수가 필요하다
# 
# 가중치 (Weights)의 개념:
# 
# RNN 셀에는 2개의 가중치 행렬이 있다:
# 
# 1. 입력 가중치 (Wx)
#    정의: 현재 입력에 곱해지는 가중치
#    특징:
#    - 입력 차원 × 셀 차원의 행렬
#    - 입력층과 셀이 완전연결되기 때문
# 
#    예시:
#    입력 특성 개수: 4개
#    셀의 뉴런 개수: 3개
#    → Wx는 4×3 = 12개의 가중치
# 
# 2. 은닉상태 가중치 (Wh)
#    정의: 이전 타임스텝의 은닉상태에 곱해지는 가중치
#    특징:
#    - 셀 차원 × 셀 차원의 행렬
#    - 이전 타임스텝의 은닉상태는 다음 타임스텝의 모든 뉴런에 연결됨
# 
#    예시:
#    셀의 뉴런 개수: 3개
#    이전 은닉상태는 현재 3개 뉴런에 모두 영향
#    → Wh는 3×3 = 9개의 가중치
# 
# 절편 (Bias):
# 정의: 각 뉴런마다 하나씩 존재
# 개수: 뉴런 개수만큼
# 예: 3개 뉴런이면 3개의 절편
# 
# 전체 파라미터 계산:
# 
# 예시: 입력 특성 4개, 셀 뉴런 3개
# 
# 파라미터 = Wx + Wh + bias
#         = (4×3) + (3×3) + 3
#         = 12 + 9 + 3
#         = 24개
# 
# 공식:
# n_params = (input_features × n_units) + (n_units × n_units) + n_units
#          = n_units * (input_features + n_units + 1)

# ============================================================================
# 6. RNN의 입력과 출력
# ============================================================================

# RNN 입력의 형태:
# 
# CNN의 입력 (합성곱 신경망):
# - 형태: 3차원 (height, width, channel)
# - 예: 28×28×1 (28×28 픽셀, 1개 채널)
# - 각 샘플이 2D 이미지
# 
# RNN의 입력 (순환 신경망):
# - 형태: 2차원 (timestep, features)
# - 한 샘플이 여러 타임스텝으로 구성
# - 각 타임스텝에서 특성 벡터가 입력됨
# - 예: 10개 단어의 문장 × 3차원 임베딩 → (10, 3) 입력
# 
# 구체적 예시: 문장 처리
# - 문장: "I am a boy" (4개 단어)
# - 각 단어를 3차원 벡터로 표현:
#   I = [0.1, 0.2, 0.3]
#   am = [0.4, 0.5, 0.6]
#   a = [0.7, 0.8, 0.9]
#   boy = [1.0, 1.1, 1.2]
# 
# - 입력 행렬 (batch 1, timestep 4, features 3):
#   [
#     [0.1, 0.2, 0.3],  ← 타임스텝 1 (단어: I)
#     [0.4, 0.5, 0.6],  ← 타임스텝 2 (단어: am)
#     [0.7, 0.8, 0.9],  ← 타임스텝 3 (단어: a)
#     [1.0, 1.1, 1.2]   ← 타임스텝 4 (단어: boy)
#   ]
#   형태: (4, 3) 또는 (1, 4, 3) if batch_size=1
# 
# RNN의 출력:
# 
# 기본 RNN 셀의 출력:
# - 마지막 타임스텝의 은닉상태만 출력
# - 형태: (batch_size, n_units)
# - 예: (1, 64) → 64차원의 벡터 1개
# 
# 왜 마지막 상태만?
# - 마지막 상태에 전체 시퀀스 정보가 축적되어 있음
# - 이 벡터 하나로 시퀀스 전체를 대표
# 
# 시각화:
# 입력: (4, 3) 시퀀스
#   t=1: [0.1, 0.2, 0.3] ──┐
#   t=2: [0.4, 0.5, 0.6] ──┤ RNN Cell
#   t=3: [0.7, 0.8, 0.9] ──┤
#   t=4: [1.0, 1.1, 1.2] ──┘
#                           ↓ (64차원 벡터)
# 출력: [0.3, 0.5, ..., 0.8] (크기 64)
# 
# 출력을 사용하는 방식:
# 
# 이진 분류 (감정 분석):
# 출력 벡터 (64) → Dense(1) → Sigmoid → [0.8] (긍정일 확률)
# 
# 다중 분류 (10개 클래스):
# 출력 벡터 (64) → Dense(10) → Softmax → [0.1, 0.05, ..., 0.7, ...]
# 
# 모든 타임스텝 출력이 필요한 경우:
# - 일부 RNN은 각 타임스텝의 은닉상태를 모두 출력할 수 있음
# - 형태: (batch_size, timestep, n_units)
# - 예: (1, 4, 64) → 각 단어의 처리 후 상태를 모두 포함
# - 용도: 다층 RNN 구축 시 다음 층의 입력으로 사용
# 
# 다층 RNN:
# 
# 첫 번째 RNN 셀:
# - 입력: (배치, 타임스텝, 입력_특성)
# - 출력 (마지막 상태만): (배치, n_units1)
# - 또는 모든 상태 출력 시: (배치, 타임스텝, n_units1)
# 
# 두 번째 RNN 셀 (첫 번째의 출력을 입력):
# - 입력: (배치, 타임스텝, n_units1) ← 첫 번째 RNN의 모든 상태
# - 출력: (배치, n_units2)
# 
# 구조:
# 입력 (4, 3)
#     ↓
# [RNN 1]: 64 units → 출력 (4, 64) ← 모든 타임스텝 출력
#     ↓
# [RNN 2]: 32 units → 출력 (32) ← 마지막 상태만
#     ↓
# [Dense]: 10 units (분류)

