# 7. 출력층의 구성
# ============================================================================

# RNN 이후의 일반적인 출력층 구조:
# 
# CNN과의 비교:
# CNN:
# - 마지막 합성곱층 출력: (배치, 높이, 너비, 채널)
# - 예: (32, 7, 7, 128)
# - Flatten 필요: (32, 6272)로 변환
# - Dense 레이어로 분류
# 
# RNN:
# - 마지막 RNN 셀 출력: (배치, n_units)
# - 예: (32, 64)
# - 이미 1차원이므로 Flatten 불필요
# - 바로 Dense 레이어 사용 가능
# 
# 다중 분류 (Multi-class Classification):
# 
# 구조:
# RNN 출력 (배치, 64)
#     ↓
# Dense(10) → 각 클래스의 로짓 (배치, 10)
#     ↓
# Softmax → 확률 분포 (배치, 10)
#     ↓
# 클래스 선택 (최대값의 인덱스)
# 
# 예시: 감정 분류 (10가지 감정)
# 출력 벡터: (32, 10)
# "행복, 슬픔, 화남, ..." 10가지 중 어느 것인지 분류
# 
# 이진 분류 (Binary Classification):
# 
# 구조:
# RNN 출력 (배치, 64)
#     ↓
# Dense(1) → 로짓 (배치, 1)
#     ↓
# Sigmoid → 확률 0~1 (배치, 1)
#     ↓
# [0] 또는 [1]로 판정
# 
# 예시: 감정 분석 (긍정/부정)
# 출력 값: 0.8 → 80% 확률로 긍정
# 출력 값: 0.2 → 20% 확률로 긍정 (즉, 80% 부정)
# 
# CNN과의 주요 차이점:
# 
# CNN:
# 1. 마지막 층 출력이 고차원 (높이×너비×채널)
# 2. Flatten으로 평탄화 필요
# 3. 그 다음 Dense 레이어
# 
# RNN:
# 1. 마지막 층 출력이 이미 1차원
# 2. Flatten 불필요
# 3. 바로 Dense 레이어 가능
# 
# 코드 예시:
# 
# # CNN + Dense
# model = Sequential([
#     Conv2D(...),
#     MaxPooling2D(...),
#     Flatten(),  ← 필수
#     Dense(128),
#     Dense(10)
# ])
# 
# # RNN + Dense
# model = Sequential([
#     SimpleRNN(64),  ← 자동으로 1차원 출력
#     Dense(128),
#     Dense(10)
# ])

