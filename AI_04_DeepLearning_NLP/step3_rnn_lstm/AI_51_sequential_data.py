# 1. 순차 데이터의 개념
# ============================================================================

# 순차 데이터(Sequential Data)란:
# 
# 정의: 순서에 의미가 있는 데이터
# 특징: 데이터의 배열 순서가 중요하다
#       순서를 바꾸면 의미가 달라지거나 없어진다
# 
# 예시 1: 텍스트 데이터
# 원본: "I am a boy"
# 의미 있는 문장
# 
# 순서 바뀐 것: "boy am a I"
# 문법적으로 성립하지 않음
# 의미 파악 불가능
# 
# 따라서 단어의 순서는 매우 중요하다
# 
# 예시 2: 시계열 데이터 (Time Series Data)
# 내일 온도를 예측하려면:
# - 지난 365일의 일별 온도가 순서대로 필요하다
# - 온도 데이터를 무작위로 섞으면 패턴 학습 불가능
# 
# 내일 주가를 예측하려면:
# - 지난 6개월의 일별 주가 추이가 필요하다
# - 날짜 순서대로 정렬되어 있어야 의미가 있다
# 
# 비교: 순서가 중요하지 않은 데이터
# 
# CNN(합성곱 신경망)과 MNIST 예제:
# - 손글씨 숫자 이미지 분류 (0-9 인식)
# - 데이터를 무작위로 섞어서 학습함 (Train/Validation 분할 시)
# - 오히려 고루 섞어주는 것이 더 좋은 결과를 냄
# - 어떤 순서로 이미지를 입력받아도 같은 숫자로 분류됨
# - 즉, MNIST에서는 데이터의 순서가 중요하지 않다
# 
# 왜 MNIST는 순서가 중요하지 않은가?
# - 각 이미지는 독립적인 샘플
# - 한 생선의 분류가 다른 생선의 분류에 영향을 주지 않음
# - 이미지 내의 픽셀 구조(공간적 관계)는 중요하지만,
#   데이터 시퀀스의 순서는 중요하지 않다
# 
# 정리:
# - 순차 데이터: 순서가 매우 중요 (텍스트, 음성, 시계열)
# - 비순차 데이터: 순서가 중요하지 않음 (이미지 분류)

