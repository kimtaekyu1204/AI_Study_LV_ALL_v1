# 순차 데이터와 RNN의 핵심:
# 
# 1. 순차 데이터:
#    - 순서가 매우 중요하다
#    - 텍스트, 음성, 시계열 데이터가 해당
#    - 순서를 바꾸면 의미가 없어진다
# 
# 2. FNN의 한계:
#    - 메모리가 없다
#    - 순차 데이터 처리에 부적합
#    - 각 샘플을 독립적으로 처리
# 
# 3. RNN의 특징:
#    - 은닉상태로 이전 정보를 기억한다
#    - 순환 구조로 정보를 누적한다
#    - 순차 데이터에 최적화
# 
# 4. 타임스텝:
#    - RNN이 시퀀스를 처리하는 한 단계
#    - 초기 상태는 0으로 시작
#    - 각 단계에서 정보가 축적된다
# 
# 5. 가중치 구성:
#    - Wx: 입력 가중치 (입력_크기 × 유닛)
#    - Wh: 은닉 가중치 (유닛 × 유닛)
#    - Bias: 절편 (유닛개수)
# 
# 6. 입력/출력:
#    - 입력: (배치, 타임스텝, 특성)
#    - 출력: (배치, 유닛) 또는 (배치, 타임스텝, 유닛)
#    - CNN보다 Flatten이 필요 없음
# 
# 7. 한계와 개선:
#    - 장기 의존성 문제 (먼 정보 손실)
#    - 해결책: LSTM, GRU (다음 주제)

