# ================================================================================
# 주요 용어 정리
# ================================================================================
# 
# - LLM (Large Language Model): 대규모 언어 모델 (GPT, BERT 등)
# - 체인 (Chain): 여러 작업을 순차적으로 연결한 워크플로
# - 프롬프트 (Prompt): LLM에 전달하는 입력 텍스트/지시사항
# - 메모리 (Memory): 대화 이력과 문맥을 저장하는 메커니즘
# - 에이전트 (Agent): LLM이 도구를 사용하여 자동으로 작업하는 시스템
# - 임베딩 (Embedding): 텍스트를 벡터로 변환하는 과정
# - 토큰 (Token): LLM이 처리하는 최소 단위 (단어의 일부)
