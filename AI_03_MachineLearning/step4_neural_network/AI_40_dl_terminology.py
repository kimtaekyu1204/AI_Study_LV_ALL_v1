# # 3. 생성적 적대 신경망 (GAN: Generative Adversarial Network)
# # ============================================================================

# GAN의 개념:
# 
# 정의: 두 개의 신경망이 경쟁하면서 진짜 같은 데이터를 생성하는 모델
# 
# 한글명: 생산적 적대 신경망 (또는 생성적 대항 신경망)
# 
# 구조:
# 1. 생성자 (Generator)
#    - 노이즈(무작위 벡터)를 받아 가짜 데이터를 생성
#    - 목표: 판별자를 속이는 더 그럴듯한 데이터 생성
#    - 학습: 판별자가 가짜라고 판정하지 않도록 개선
# 
# 2. 판별자 (Discriminator)
#    - 진짜 데이터와 가짜 데이터를 구분
#    - 목표: 생성자가 만든 데이터를 정확하게 거짓으로 탐지
#    - 학습: 진짜와 가짜를 점점 더 잘 구분하도록 개선
# 
# 경쟁 메커니즘:
# - 생성자와 판별자가 서로를 이기려고 경쟁
# - 생성자: 더 그럴듯한 데이터 만들기
# - 판별자: 더 정확하게 구분하기
# - 두 네트워크가 함께 발전
# - 결과적으로 판별자를 속일 만큼 그럴듯한 데이터 생성
# 
# 활용 분야:
# - 이미지 생성 (StyleGAN, BigGAN)
# - 스타일 변환 (사진 → 그림)
# - 이미지 확대 (해상도 향상)
# - 얼굴 합성
# - 데이터 생성 (부족한 데이터 보충)
# 
# 훈련 과정 (간단한 설명):
# 1. 생성자: 노이즈 → 가짜 이미지 생성
# 2. 판별자: [진짜 이미지, 가짜 이미지] → 진짜/가짜 판정
# 3. 손실 계산 및 역전파:
#    - 생성자: 판별자가 가짜라고 판정하지 않도록
#    - 판별자: 진짜/가짜를 정확하게 구분하도록
# 4. 반복
# 
# 예시:
# 얼굴 생성 GAN:
# - 생성자: 무작위 벡터 → 새로운 얼굴 이미지 생성
# - 판별자: 생성된 얼굴이 진짜인지 판정
# - 충분한 학습 후: 존재하지 않는 얼굴을 매우 그럴듯하게 생성 가능

