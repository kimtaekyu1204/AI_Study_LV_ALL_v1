# # 2. 합성곱 신경망 (CNN: Convolutional Neural Network)
# # ============================================================================

# CNN의 개념:
# 
# 정의: 이미지 데이터에 특화된 신경망 구조
# 
# 한글명: 합성곱 신경망
# 
# 주요 특징:
# - 이미지의 공간적 특성을 효과적으로 학습
# - 완전연결층보다 훨씬 적은 파라미터 (효율적)
# - 이미지의 국소적 특징을 감지
# 
# 구조:
# 1. 합성곱층 (Convolutional Layer)
#    - 작은 필터(커널)를 이미지 위에서 이동시키며 특징 추출
#    - 엣지, 패턴 등의 낮은 수준 특징 감지
# 
# 2. 풀링층 (Pooling Layer)
#    - 특징 맵의 크기를 줄인다
#    - 공간적 차원 축소로 계산량 감소
#    - 최대 풀링: 가장 큰 값만 선택
#    - 평균 풀링: 평균값 선택
# 
# 3. 완전연결층 (Fully Connected Layer)
#    - 추출된 특징을 바탕으로 분류
#    - 신경망의 최종 분류 레이어
# 
# 활용 분야:
# - 이미지 분류 (ImageNet, MNIST)
# - 물체 검출 (YOLO, Faster R-CNN)
# - 의료 영상 분석 (X-ray, MRI)
# - 얼굴 인식
# 
# 대표 모델:
# - LeNet: 최초의 CNN
# - AlexNet: ImageNet 우승 (2012년)
# - VGGNet: 깊은 신경망 구조
# - ResNet: 잔차 연결 도입
# - Inception: 다중 스케일 특징
# 
# 예시:
# MNIST (손글씨 숫자 인식):
# 28x28 픽셀 이미지 → CNN → 10개 클래스 분류 (0-9)
# - 합성곱층: 숫자의 획 패턴 학습
# - 풀링층: 위치 변화 불변성 추가
# - 완전연결층: 최종 분류

