# # 1. 손실 함수 (Loss Function)
# # ============================================================================

# 손실 함수의 개념:
# 
# 정의: 모델의 예측값과 실제값 사이의 오차를 정량화하는 함수
# 
# 역할:
# - 모델이 얼마나 잘못 예측했는지 수치로 나타낸다.
# - 신경망이 학습하는 방향을 결정한다.
# - 손실을 최소화하는 방향으로 가중치를 업데이트한다.
# 
# 손실 함수의 특징:
# - 낮을수록 좋다 (모델이 잘 예측했다는 의미)
# - 미분 가능해야 한다 (역전파에 필요)
# - 문제에 따라 다른 손실 함수를 선택한다.
# 
# 예시: 두 점 사이의 거리로 오차 계산
# 실제값: 100, 예측값: 105
# 오차 = |100 - 105| = 5
# 
# 만약 단순 뺄셈만 사용하면:
# - 105 - 100 = 5
# - 하지만 여러 값의 오차를 합치면 서로 상쇄될 수 있다:
#   (105 - 100) + (78 - 80) = 5 + (-2) = 3 (실제 차이는 7인데 3으로 계산됨)
# 
# 따라서 제곱을 사용해서 모든 오차를 양수로 만든다:
# - (105 - 100)² + (78 - 80)² = 25 + 4 = 29
# 
# 주요 손실 함수:
# 
# 1. 평균 제곱 오차 (MSE: Mean Squared Error)
#    - 정의: 모든 오차를 제곱해서 평균을 구한다
#    - 계산: MSE = (1/n) × Σ(y - ŷ)²
#    - 용도: 회귀 문제
#    - 특징: 큰 오차에 더 큰 패널티를 준다
# 
#    예시:
#    실제: [100, 80], 예측: [105, 78]
#    MSE = ((100-105)² + (80-78)²) / 2
#        = (25 + 4) / 2
#        = 14.5
# 
# 2. 교차 엔트로피 (Cross-Entropy)
#    - 정의: 확률 분포 사이의 차이를 측정한다
#    - 계산: CE = -Σ y × log(ŷ)
#    - 용도: 분류 문제 (특히 신경망)
#    - 특징: 확률 기반, 카테고리컬 데이터에 최적화
# 
# 3. 이진 교차 엔트로피 (Binary Cross-Entropy)
#    - 정의: 교차 엔트로피의 이진 분류 버전
#    - 용도: 이진 분류 (참/거짓, 긍정/부정)
#    - 특징: 0 또는 1의 레이블
# 
# 4. L1 손실 (Mean Absolute Error, MAE)
#    - 정의: 절댓값 오차의 평균
#    - 계산: MAE = (1/n) × Σ|y - ŷ|
#    - 특징: MSE보다 이상값에 덜 민감함

