# 활성화 함수 (Activation Function):
# - 정의: 신경망의 뉴런에 비선형성을 추가하는 함수
# - 목적: 선형 변환만으로는 복잡한 패턴을 학습할 수 없다
# - 종류:
#   * ReLU: 가장 널리 사용 (음수는 0, 양수는 그대로)
#   * Sigmoid: 0~1로 정규화 (이진 분류 출력층)
#   * Tanh: -1~1로 정규화
#   * Softmax: 확률 분포로 변환 (다중 분류 출력층)
# 
# 역전파 (Backpropagation):
# - 정의: 출력층에서 입력층으로 오차를 역방향으로 전파
# - 목적: 각 가중치가 오차에 얼마나 기여하는지 계산
# - 결과: 가중치 업데이트 방향 결정
# 
# 옵티마이저 (Optimizer):
# - 정의: 손실 함수를 최소화하는 가중치 업데이트 방법
# - 종류:
#   * SGD: 기본 그래디언트 하강법
#   * Adam: 현대적이고 효과적 (가장 널리 사용)
#   * RMSprop: 적응형 학습률
#   * Momentum: 이전 방향을 반영
# 
# 배치 정규화 (Batch Normalization):
# - 정의: 각 배치의 입력을 정규화
# - 목적: 학습을 안정화하고 빠르게 만듦
# - 효과: 더 높은 학습률 가능, 가중치 초기화 덜 민감
# 
# 드롭아웃 (Dropout):
# - 정의: 학습 중 무작위로 뉴런을 비활성화
# - 목적: 과적합 방지
# - 특징: 테스트 시에는 적용하지 않음
# 
# 에포크 (Epoch):
# - 정의: 전체 학습 데이터를 한 번 통과
# - 예: 10 에포크 = 전체 데이터를 10번 반복 학습
# 
# 배치 (Batch):
# - 정의: 한 번에 처리하는 데이터의 개수
# - 예: 배치 크기 32 = 32개씩 묶어서 처리
# - 이유: GPU 병렬 처리, 메모리 효율성
# 
# 하이퍼파라미터 (Hyperparameter):
# - 정의: 학습 과정에서 수동으로 설정하는 값
# - 예:
#   * 학습률 (Learning Rate)
#   * 배치 크기 (Batch Size)
#   * 에포크 수 (Number of Epochs)
#   * 은닉층 뉴런 수
#   * 드롭아웃 비율
# 
# 과적합 (Overfitting):
# - 정의: 모델이 학습 데이터에 너무 맞춰져서 새로운 데이터에서 성능 저하
# - 증상: 학습 손실은 감소, 검증 손실은 증가
# - 해결: 드롭아웃, 정규화, 조기 중단
# 
# 전이 학습 (Transfer Learning):
