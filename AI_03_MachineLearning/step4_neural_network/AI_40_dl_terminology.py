# Keras의 개요:
# 
# 정의: 파이썬으로 작성된 고수준 신경망 API
# 
# 개발자: François Chollet (프랑소와 숄레)
# 
# 개발 시기: 2015년 3월 출시
# 
# 특징:
# 1. 사용자 친화성
#    - 간단한 API로 빠르게 신경망 구축 가능
#    - 초보자도 쉽게 배울 수 있다
#    - 코드가 직관적이고 읽기 쉽다
# 
# 2. 모듈성
#    - 레이어, 활성화 함수, 손실 함수를 독립적으로 조합
#    - 원하는 아키텍처를 자유롭게 구성
# 
# 3. 확장성
#    - 새로운 레이어나 손실 함수 추가 가능
#    - 사용자 정의 컴포넌트 작성 가능
# 
# 지원하는 신경망:
# - 완전연결 신경망 (Dense Network)
# - 합성곱 신경망 (CNN)
# - 순환 신경망 (RNN, LSTM, GRU)
# - 하이브리드 모델 (CNN + RNN 등)
# 
# 백엔드 (Backend):
# 정의: Keras가 실제 GPU 연산을 수행하는 기본 라이브러리
# 
# 특징:
# - Keras는 직접 GPU 연산을 하지 않는다
# - 대신 다른 라이브러리를 백엔드로 사용한다
# - 동일한 Keras 코드로 다양한 백엔드 활용 가능
# 
# 지원하는 백엔드:
# 1. TensorFlow (현재 기본)
#    - 구글 개발
#    - 가장 널리 사용됨
#    - 성능 우수
# 
# 2. CNTK (Cognitive Toolkit)
#    - 마이크로소프트 개발
#    - 현재 거의 사용되지 않음
# 
# 3. Theano
#    - 구식 백엔드
#    - 현재 개발 중단
# 
# 장점:
# - Keras API만 배우면 백엔드 변경 용이
# - 다양한 라이브러리 선택 가능
# - "멀티-백엔드 케라스"라고도 불림
# 
# 예시 코드:
# ```python
# from keras.models import Sequential
# from keras.layers import Dense
# 
# # 모델 생성
# model = Sequential([
